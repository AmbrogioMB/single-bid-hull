"""Table and numbers of the paper from the result CSVs: python make_table.py [results folder]

Reads <folder>/{period,day}/*.csv (default: results; all formulations of a task are solved by the
same process, so times are paired) and keeps only the test days in dates.txt. Writes
<folder>/table_results.tex (rows: instance kind and branching factor, instances with eta > 0) and
<folder>/numbers.txt with every number quoted in the text.

Definitions (V = optimal values; single-bid optimum = disjunctive MILP, solved to optimality):
  curve value (EUR)      V_hull - V_single
  intraday gain (EUR)    V_single - V_none, V_none = objective with no intraday bid
  curve value (%)        100 (V_hull - V_single) / (V_single - V_none)
  LP opt.                share of instances with V_hull - V_single <= 1e-6 max(1, |V_single|)
  root gap big-M (%)     100 (V_bigm_LP - V_single) / max(1, |V_single|)
  times                  solver time (model.optimize), seconds
"""
import glob
import os
import sys

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
OPTIMAL, TIME_LIMIT = 2, 9
TOL = 1e-6
HEADER = r"""\begin{tabular}{lrrrrrrrrrr}
\toprule
& & & \multicolumn{3}{c}{Curve value} & LP opt. & Root gap & \multicolumn{3}{c}{Time (s)}\\
\cmidrule(lr){4-6} \cmidrule(lr){9-11}
Inst. & $b$ & Leaves & EUR & \% mean & \% max & (\%) & big-M (\%) & disj. & indic. & big-M\\
\midrule
"""
FOOTER = r"""\bottomrule
\end{tabular}
"""


def test_days():
    with open(os.path.join(HERE, "dates.txt")) as f:
        return {line.strip() for line in f if line.strip() and not line.startswith("#")}


def load(folder, parts):
    files = [f for p in parts for f in glob.glob(os.path.join(folder, p, "*.csv"))]
    rows = pd.concat((pd.read_csv(f) for f in files), ignore_index=True)
    return rows[rows["date"].astype(str).isin(test_days())].reset_index(drop=True)


def add_measures(rows):
    best = rows["disj_objective"].where(rows["disj_status"] == OPTIMAL)
    scale = best.abs().clip(lower=1.0)
    rows["curve_eur"] = rows["hull_objective"] - best
    rows["gain_eur"] = best - rows["no_trade"]
    rows["curve_pct_gain"] = 100 * rows["curve_eur"] / rows["gain_eur"].where(rows["gain_eur"] > 0)
    rows["curve_pct_total"] = 100 * rows["curve_eur"] / scale
    rows["integral"] = rows["curve_eur"] <= TOL * scale
    if "bigm_lp_objective" in rows:
        rows["bigm_root_gap"] = 100 * (rows["bigm_lp_objective"] - best) / scale
    return rows, scale


def fmt(x, digits):
    if x is None or (isinstance(x, float) and np.isnan(x)):
        return "--"
    if 0 < abs(x) < 0.5 * 10**-digits:
        return f"$<${10**-digits:.{digits}f}"
    return f"{x:.{digits}f}"


def secs(x):
    return "$<$0.01" if x < 0.005 else (f"{x:.2f}" if x < 10 else f"{x:.0f}")


def main():
    folder = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "results")
    rows, scale = add_measures(load(folder, ["period", "day"]))
    out = []
    lines = []
    risk = rows[rows["eta"] > 0]
    for kind in ["period", "day"]:
        for b, g in risk[risk["kind"] == kind].groupby("branching"):
            r = {
                "kind": kind, "b": b, "instances": len(g), "leaves": g["leaves"].mean(),
                "curve_eur": g["curve_eur"].mean(), "curve_pct_mean": g["curve_pct_gain"].mean(),
                "curve_pct_max": g["curve_pct_gain"].max(), "integral": 100 * g["integral"].mean(),
                "root_gap": g["bigm_root_gap"].mean(), "disj_s": g["disj_seconds"].mean(),
                "ind_s": g["ind_seconds"].mean(), "ind_to": int((g["ind_status"] == TIME_LIMIT).sum()),
                "bigm_s": g["bigm_seconds"].mean(), "bigm_to": int((g["bigm_status"] == TIME_LIMIT).sum()),
            }
            out.append(r)
            lines.append(
                f"{'Period' if kind == 'period' else 'Day'} & {b} & {r['leaves']:.0f} & {fmt(r['curve_eur'], 2)} & "
                f"{fmt(r['curve_pct_mean'], 2)} & {fmt(r['curve_pct_max'], 1)} & {r['integral']:.0f} & "
                f"{fmt(r['root_gap'], 2)} & {secs(r['disj_s'])} & {secs(r['ind_s'])} ({r['ind_to']}) & "
                f"{secs(r['bigm_s'])} ({r['bigm_to']})\\\\"
            )
    with open(os.path.join(folder, "table_results.tex"), "w", newline="\n") as f:
        f.write("% Generated by make_table.py. Do not edit.\n")
        f.write(HEADER + "\n".join(lines) + "\n" + FOOTER)
    table = pd.DataFrame(out)

    # Numbers quoted in the text.
    n = []
    e0, rk = rows[rows["eta"] == 0], rows[rows["eta"] > 0]
    n.append(f"tasks {len(rows)}; eta=0 by kind {e0.groupby('kind').size().to_dict()}; eta>0 per kind/b "
             f"{rk.groupby(['kind', 'branching']).size().to_dict()}")
    rel = lambda a, b: (a - b).abs() / b.abs().clip(lower=1.0)  # noqa: E731
    n.append(f"eta=0: max rel |closed form - hull| {rel(e0['closed_form'], e0['hull_objective']).max():.2e}; "
             f"max rel |disj - hull| {rel(e0['disj_objective'], e0['hull_objective']).max():.2e}; "
             f"all disj optimal {bool((e0['disj_status'] == OPTIMAL).all())}")
    n.append(f"observations: period mean {rows[rows.kind == 'period'].observations.mean():.0f} "
             f"(min {rows[rows.kind == 'period'].observations.min()}), day mean "
             f"{rows[rows.kind == 'day'].observations.mean():.0f} (min {rows[rows.kind == 'day'].observations.min()}, "
             f"max {rows[rows.kind == 'day'].observations.max()})")
    for kind in ["period", "day"]:
        g = rk[rk.kind == kind]
        n.append(f"{kind} eta>0: curve EUR mean {g.curve_eur.mean():.4f} max {g.curve_eur.max():.4f}; "
                 f"% of intraday gain mean {g.curve_pct_gain.mean():.4f} max {g.curve_pct_gain.max():.3f}; "
                 f"% of total mean {g.curve_pct_total.mean():.5f} max {g.curve_pct_total.max():.4f}; "
                 f"intraday gain EUR mean {g.gain_eur.mean():.2f} (min {g.gain_eur.min():.2f}); "
                 f"LP opt {100 * g.integral.mean():.1f}%; big-M root gap mean {g.bigm_root_gap.mean():.3f}% "
                 f"max {g.bigm_root_gap.max():.2f}%")
    n.append(f"LP opt range by row: {table.integral.min():.0f}-{table.integral.max():.0f}%")
    n.append(f"disj: all optimal {bool((rows.disj_status == OPTIMAL).all())}; max solver s "
             f"{rows.disj_seconds.max():.3f}; share root (nodes<=1) {100 * (rows.disj_nodes <= 1).mean():.2f}%; "
             f"max build s {rows.disj_build_seconds.max():.2f} (day mean {rows[rows.kind == 'day'].disj_build_seconds.mean():.2f})")
    d = rk[(rk.kind == "day") & (rk.branching >= 3)]
    n.append(f"day eta>0 b>=3: big-M time-outs {(d.bigm_status == TIME_LIMIT).sum()} of {len(d)}; "
             f"indicator time-outs {(d.ind_status == TIME_LIMIT).sum()}")
    dd = rk[rk.kind == "day"]
    n.append(f"day eta>0: median paired ratio ind/disj {(dd.ind_seconds / dd.disj_seconds).median():.1f}; "
             f"bigm/disj (optimal only) {(dd.bigm_seconds / dd.disj_seconds)[dd.bigm_status == OPTIMAL].median():.1f}; "
             f"ind mean s by b {dd.groupby('branching').ind_seconds.mean().round(1).to_dict()}")
    for name in ["ind", "bigm"]:
        diff = (rows[f"{name}_objective"] - rows["disj_objective"]) / scale
        opt = rows[f"{name}_status"] == OPTIMAL
        tl = rows[f"{name}_status"] == TIME_LIMIT
        below = opt & (diff < -TOL)
        gaps = rows["pairs_below_eps"] > 0
        n.append(f"{name}: optimal {int(opt.sum())}, time limit {int(tl.sum())}; above disj (optimal) "
                 f"{int((opt & (diff > TOL)).sum())}; below by >1e-6 (optimal) {int(below.sum())}, max "
                 f"{-diff[opt].min():.2e}; of these on trees with a price gap < eps: {int((below & gaps).sum())}; "
                 f"time-limited incumbents below {int((tl & (diff < -TOL)).sum())}, max {-diff[tl].min() if tl.any() else 0:.2e}")
    n.append(f"trees with a price gap < eps: period {int((rows[rows.kind == 'period'].pairs_below_eps > 0).sum())} of "
             f"{int((rows.kind == 'period').sum())}, day {int((rows[rows.kind == 'day'].pairs_below_eps > 0).sum())} of "
             f"{int((rows.kind == 'day').sum())}; min gap {rows.min_price_gap.min():.2e}")
    # Sensitivity to the bid bound.
    for kind in ["period", "day"]:
        parts = sorted(os.path.basename(p) for p in glob.glob(os.path.join(folder, f"{kind}_s*")))
        for part in parts:
            s, _ = add_measures(load(folder, [part]))
            n.append(f"sensitivity {part}: n {len(s)}, curve % of gain mean {s.curve_pct_gain.mean():.4f} max "
                     f"{s.curve_pct_gain.max():.3f}, EUR mean {s.curve_eur.mean():.3f}, LP opt {100 * s.integral.mean():.1f}%")
        base = rk[(rk.kind == kind) & (rk.branching == 3)]
        n.append(f"sensitivity {kind}_s0.1 (main runs, b = 3): n {len(base)}, curve % of gain mean "
                 f"{base.curve_pct_gain.mean():.4f} max {base.curve_pct_gain.max():.3f}, EUR mean "
                 f"{base.curve_eur.mean():.3f}, LP opt {100 * base.integral.mean():.1f}%")
    text = "\n".join(n)
    with open(os.path.join(folder, "numbers.txt"), "w", newline="\n") as f:
        f.write(text + "\n")
    with pd.option_context("display.width", 220, "display.max_columns", 30):
        print(table.round(4).to_string(index=False))
    print(text)


if __name__ == "__main__":
    main()
